// 阶段顺序
const stageOrder = ['需求阶段', '设计阶段', '执行阶段', '验收阶段', '售后阶段'];

function listTemplates() {
  return templates.map(t => ({ key: t.key, name: t.name, icon: t.icon, stage: t.stage, phase: t.phase, purpose: t.purpose, audience: t.audience }));
}
// 按阶段分组（供前端渲染交付物模板中心）
function listByStage() {
  return stageOrder.map(stage => ({
    stage,
    ...stageMeta[stage],
    items: templates.filter(t => t.stage === stage).map(t => ({
      key: t.key, name: t.name, icon: t.icon, phase: t.phase, purpose: t.purpose, audience: t.audience,
      tips: t.tips, outline: t.outline, source: t.source
    }))
  }));
}
function getTemplate(key) {
  return templates.find(t => t.key === key) || null;
}

module.exports = { templates, stageMeta, stageOrder, listTemplates, listByStage, getTemplate };
